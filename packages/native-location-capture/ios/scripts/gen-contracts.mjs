// Writes ios/Sources/CaptureCore/Contracts.generated.swift from the contract files in
// packages/shared/contracts, so the Swift module never restates a statement or a cipher value.
// Run from anywhere: `node packages/native-location-capture/ios/scripts/gen-contracts.mjs`.
// ContractTests.swift fails when the committed file and the JSON disagree, so a forgotten run
// shows up in `swift test`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '../../../shared/contracts');
const read = (name) => JSON.parse(readFileSync(join(contracts, name), 'utf8'));

const writer = read('native-writer.json');
const cipher = read('cipher-params.json');
const geo = read('geo-vectors.json');

// JSON string syntax is also valid Swift string-literal syntax for these values.
const str = (value) => JSON.stringify(value);
const list = (values) => `[${values.map(str).join(', ')}]`;

const applyPragmas = [
  `PRAGMA cipher_compatibility = ${cipher.cipherCompatibility}`,
  `PRAGMA cipher_page_size = ${cipher.pageSizeBytes}`,
  `PRAGMA kdf_iter = ${cipher.kdfIterations}`,
  `PRAGMA cipher_kdf_algorithm = ${cipher.kdfAlgorithm}`,
  `PRAGMA cipher_hmac_algorithm = ${cipher.hmacAlgorithm}`,
];
const readBack = [
  ['cipher_page_size', String(cipher.pageSizeBytes)],
  ['kdf_iter', String(cipher.kdfIterations)],
  ['cipher_kdf_algorithm', cipher.kdfAlgorithm],
  ['cipher_hmac_algorithm', cipher.hmacAlgorithm],
];

const swift = `// GENERATED by ios/scripts/gen-contracts.mjs from packages/shared/contracts/native-writer.json,
// cipher-params.json and geo-vectors.json. Do not edit; change the contract and run the script.

/// Everything this module may do to the store (packages/shared/src/store/nativeWriter.ts).
enum StoreContract {
    static let schemaVersion = ${writer.schemaVersion}
    static let readSchemaVersionSql = ${str(writer.readSchemaVersionSql)}
    static let storeFileName = ${str(writer.storeFileName)}
    static let insertLocationSampleSql = ${str(writer.insertLocationSampleSql)}
    static let insertVisitStaySql = ${str(writer.insertVisitStaySql)}
    static let closeVisitStaySql = ${str(writer.closeVisitStaySql)}
    static let sampleSources: [String] = ${list(writer.sampleSources)}
    static let retentionSec: Int64 = ${writer.retentionSec}
    static let deleteSamplesBeforeSql = ${str(writer.deleteSamplesBeforeSql)}
    static let deleteStaysEndedBeforeSql = ${str(writer.deleteStaysEndedBeforeSql)}
    static let trimStaysStartedBeforeSql = ${str(writer.trimStaysStartedBeforeSql)}
    static let rewindStayCursorSql = ${str(writer.rewindStayCursorSql)}
}

/// The pinned SQLCipher parameters of the store (packages/shared/src/store/cipher.ts).
enum CipherParams {
    static let sqlcipherMajor = ${cipher.sqlcipherMajor}
    static let keyBytes = ${cipher.keyBytes}
    static let journalMode = ${str(cipher.journalMode)}
    /// Run right after the key is set and before the first read, in this order.
    static let applyPragmas: [String] = [
${applyPragmas.map((pragma) => `        ${str(pragma)},`).join('\n')}
    ]
    /// Pragma name and the value that must be read back after opening.
    static let readBack: [(pragma: String, expected: String)] = [
${readBack.map(([pragma, expected]) => `        (${str(pragma)}, ${str(expected)}),`).join('\n')}
    ]
}

/// Constants of the shared distance function (packages/shared/src/geo/distance.ts).
enum GeoContract {
    static let earthRadiusM: Double = ${geo.earth_radius_m}
}
`;

writeFileSync(join(here, '../Sources/CaptureCore/Contracts.generated.swift'), swift);
